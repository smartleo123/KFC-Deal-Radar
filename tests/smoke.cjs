const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const listeners={};
const sandbox={window:{},document:{readyState:'loading',addEventListener:(name,cb)=>listeners[name]=cb},localStorage:{getItem:()=>null},Date,Intl,Number,String,Math,Set,Object,Array,JSON,RegExp,console};
vm.runInNewContext(fs.readFileSync('app.js','utf8'),sandbox);
const {norm,drinksFor,referencePrice,enrich,matchingFoodGroups,withinBudget,mergeCouponLists,isValidOnDate}=sandbox.window.__KFC_RADAR_TEST__;
assert.equal(norm(' 雞 腿 '),'雞腿');
const deal={coupon_code:12345,name:'測試套餐',price:90,items:[{name:'可樂(中)',count:1,flavors:[]},{name:'雞腿堡',count:1,flavors:[]}]};
const singles={'可樂(中)':{price:35},'雞腿堡':{price:95}};
assert.equal(drinksFor(deal).length,1);
assert.equal(referencePrice(deal,singles),130);
assert.equal(enrich(deal,singles).percent,30.8);
assert.equal(enrich({...deal,items:[{name:'未知品項',count:1}]},singles).percent,null);
const option={items:[{name:'雞腿堡',count:1,flavors:[{name:'冰紅茶'}]}]};
assert.equal(drinksFor(option,false).length,0);
assert.equal(drinksFor(option,true).length,1);
const burger={items:[{name:'咔啦雞腿堡',count:1},{name:'冰紅茶',count:1}]};
const chicken={items:[{name:'咔啦脆雞',count:2},{name:'香酥脆薯(中)',count:1}]};
assert.equal(matchingFoodGroups(burger)['漢堡'],true);
assert.equal(matchingFoodGroups(burger)['炸雞'],false);
assert.equal(matchingFoodGroups(chicken)['炸雞'],true);
assert.equal(matchingFoodGroups(chicken)['漢堡'],false);
assert.equal(matchingFoodGroups(burger)['飲料'],true);
assert.equal(withinBudget(150,'100','200'),true);
assert.equal(withinBudget(99,'100','200'),false);
assert.equal(withinBudget(250,'100','200'),false);
assert.equal(withinBudget(150,'',''),true);
assert.equal(withinBudget(100,'150','100'),false);
const officialItem={coupon_code:50521,price:40,items:[{name:'雞腿堡',count:1}],source:'kfc_api_verified'};
const communitySame={coupon_code:50521,price:99,items:[{name:'雞腿堡',count:1}]};
const communityExtra={coupon_code:50522,price:59,items:[{name:'可樂',count:1}]};
const merged=mergeCouponLists([officialItem],[communitySame,communityExtra]);
assert.equal(merged.length,2);
assert.equal(merged.find(x=>x.coupon_code===50521).price,40);
assert.equal(merged.find(x=>x.coupon_code===50521).source,'kfc_api_verified');
assert.equal(merged.find(x=>x.coupon_code===50522).source,'community_unverified');
assert.equal(isValidOnDate({end_date:'2026-11-23'},new Date('2026-11-15T00:00:00+08:00').getTime()),true);
assert.equal(isValidOnDate({end_date:'2026-11-10'},new Date('2026-11-15T00:00:00+08:00').getTime()),false);
console.log('Smoke tests passed');