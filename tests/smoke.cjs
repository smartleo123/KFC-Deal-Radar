const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const listeners={};
const sandbox={window:{},document:{readyState:'loading',addEventListener:(name,cb)=>listeners[name]=cb},localStorage:{getItem:()=>null},Date,Intl,Number,String,Math,Set,Object,Array,JSON,RegExp,console};
vm.runInNewContext(fs.readFileSync('app.js','utf8'),sandbox);
const {money,norm,drinksFor,referencePrice,referencePriceInfo,enrich,matchingFoodGroups,withinBudget,mergeCouponLists,isValidOnDate}=sandbox.window.__KFC_RADAR_TEST__;
assert.equal(norm(' 雞 腿 '),'雞腿');
const deal={coupon_code:12345,name:'測試套餐',price:90,items:[{name:'可樂(中)',count:1,flavors:[]},{name:'雞腿堡',count:1,flavors:[]}]};
const singles={'可樂(中)':{price:35},'雞腿堡':{price:95}};
assert.equal(drinksFor(deal).length,1);
assert.equal(referencePrice(deal,singles),130);
assert.equal(enrich(deal,singles).percent,30.8);
assert.equal(enrich({...deal,items:[{name:'未知品項',count:1}]},singles).percent,null);
const option={items:[{name:'雞腿堡',count:1,flavors:[{name:'冰紅茶'}]}]};
assert.equal(drinksFor(option,false).length,0);
assert.equal(drinksFor(option,true).length,1);
const burger={items:[{name:'咔啦雞腿堡',count:1},{name:'冰紅茶',count:1}]};
const chicken={items:[{name:'咔啦脆雞',count:2},{name:'香酥脆薯(中)',count:1}]};
assert.equal(matchingFoodGroups(burger)['漢堡'],true);
assert.equal(matchingFoodGroups(burger)['炸雞'],false);
assert.equal(matchingFoodGroups(chicken)['炸雞'],true);
assert.equal(matchingFoodGroups(chicken)['漢堡'],false);
assert.equal(matchingFoodGroups(burger)['飲料'],true);
assert.equal(withinBudget(150,'100','200'),true);
assert.equal(withinBudget(99,'100','200'),false);
assert.equal(withinBudget(250,'100','200'),false);
assert.equal(withinBudget(150,'',''),true);
assert.equal(withinBudget(100,'150','100'),false);
const officialItem={coupon_code:50521,price:40,items:[{name:'雞腿堡',count:1}],source:'kfc_api_verified'};
const communitySame={coupon_code:50521,price:99,items:[{name:'雞腿堡',count:1}]};
const communityExtra={coupon_code:50522,price:59,items:[{name:'可樂',count:1}]};
const merged=mergeCouponLists([officialItem],[communitySame,communityExtra]);
assert.equal(merged.length,2);
assert.equal(merged.find(x=>x.coupon_code===50521).price,40);
assert.equal(merged.find(x=>x.coupon_code===50521).source,'kfc_api_verified');
assert.equal(merged.find(x=>x.coupon_code===50522).source,'community_unverified');
assert.equal(isValidOnDate({end_date:'2026-11-23'},new Date('2026-11-15T00:00:00+08:00').getTime()),true);
assert.equal(isValidOnDate({end_date:'2026-11-10'},new Date('2026-11-15T00:00:00+08:00').getTime()),false);
const officialMenu={
 '原味蛋撻':{price:49},'冰無糖綠茶(小)':{price:35},
 '上校雞塊4塊':{price:49},'香酥脆薯(小)':{price:41},
 '百事可樂(中)':{price:38},'咔啦脆雞':{price:70}
};
const officialBundle={coupon_code:50521,price:38,items:[{name:'百事可樂(中)',count:2}]};
assert.equal(referencePriceInfo(officialBundle,{},officialMenu).price,76);
assert.equal(referencePriceInfo(officialBundle,{},officialMenu).source,'official');
assert.equal(enrich(officialBundle,{},officialMenu).percent,50);
const combo={items:[{name:'2入原味蛋撻',count:1},{name:'無糖綠茶(小)',count:1}]};
assert.equal(referencePrice(combo,{},officialMenu),133);
assert.equal(referencePrice({items:[{name:'4塊雞塊+小薯',count:1}]},{},officialMenu),90);
assert.equal(referencePrice({items:[{name:'咔啦脆雞(辣)',count:2},{name:'糖醋醬',count:1}]},{},officialMenu),140);
assert.equal(referencePrice({items:[{name:'10顆雙色轉轉QQ球',count:1}]},{},officialMenu),null);
assert.equal(referencePrice({items:[{name:'沒有官網定價的特殊餐',count:1}]},{},officialMenu),null);
const fallbackC={items:[{name:'咔啦雞腿堡(辣)',count:1},{name:'原味蛋撻',count:1}]};
const thirdParty={'咔啦雞腿堡(辣)':{price:120}};
assert.equal(referencePriceInfo(fallbackC,thirdParty,officialMenu).price,169);
assert.equal(referencePriceInfo(fallbackC,thirdParty,officialMenu).source,'mixed');
// Regression: future/expired coupons must not be shown before/after their valid window.
assert.equal(isValidOnDate({start_date:'2026-11-20',end_date:'2026-12-20'},new Date('2026-11-16T12:00:00+08:00').getTime()),false);
assert.equal(isValidOnDate({start_date:'2026/11/14',end_date:'2026/11/20'},new Date('2026-11-16T12:00:00+08:00').getTime()),true);
assert.equal(isValidOnDate({start_date:'2026-11-01',end_date:'2026-11-15'},new Date('2026-11-16T12:00:00+08:00').getTime()),false);
assert.equal(isValidOnDate({end_date:'not-a-date'},new Date('2026-11-16T12:00:00+08:00').getTime()),false);
assert.equal(enrich({coupon_code:123,price:null,items:[]},{}),null);
assert.equal(enrich({coupon_code:123,price:'',items:[]},{}),null);
assert.equal(money(38.5),'NT$38.5');
assert.equal(money(38.25),'NT$38.25');
assert.equal(enrich({coupon_code:12345,price:150,original_price:120,items:[]},{}).saving,null);
console.log('Smoke tests passed');